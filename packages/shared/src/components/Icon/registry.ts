let complete = false;
let loading: Promise<void> | undefined;

export function registerIconNamespace(namespace: object): void {
  if (complete) return;
  Object.defineProperties(icons, Object.getOwnPropertyDescriptors(namespace));
  complete = true;
}

export function getIcon(name: string): ComponentType<any> | undefined {
  const existing = icons[name];
  if (existing || complete) return existing;
  if (!loading) {
    loading = import('@kubed/icons').then(namespace => {
      registerIconNamespace(namespace);
    });
  }
  throw loading;
}
